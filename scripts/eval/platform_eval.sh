#!/usr/bin/env bash
# platform_eval.sh — before/after guardrail for the cursor-purge + crew-default
# program (docs/gaps/ADF_CURSOR_PURGE_AND_CREW_SPEC.md). Measures the automatable
# success criteria C1-C5, C8 as fast static proxies. The live build E2E (C6/C7/C10)
# and the full regression (C9) are run separately. Exit 0 only when all measured
# criteria meet target — so it doubles as a CI gate.
set -uo pipefail
cd "$(dirname "$0")/../.."  # repo root
LIB=tools/orchestration_server/lib
BIN=tools/orchestration_server/bin
DASH=tools/orchestration_dashboard/lib

fail=0
pass() { printf "  ✅ %s\n" "$1"; }
miss() { printf "  ❌ %s\n" "$1"; fail=1; }

echo "===== ADF platform eval — $(date '+%Y-%m-%d %H:%M') ====="

# C1 — cursor-the-tool references in active code (excl tests/docs/.cursor data path)
c1=$(grep -rIn -E "cursor-agent|RunnerKind\.cursor|CursorBackend|run_server_cursor|setup_cursor|ADF_STUDIO_BACKEND|prefer_cursor|cursor_cli|CURSOR_API_KEY|chat_cursor|cursorCommand|cursor_command" \
  --include='*.dart' --include='*.py' --include='*.sh' "$LIB" "$BIN" "$DASH" scripts install 2>/dev/null \
  | grep -v "/test/" | grep -v "scripts/eval/" | grep -vc "\.adf/orchestration")
[ "$c1" -eq 0 ] && pass "C1 cursor-tool refs == 0 (got $c1)" || miss "C1 cursor-tool refs == 0 (got $c1)"

# C2 — cursor tool scripts/adapters on disk
c2=$(ls -1 scripts/orch/run_server_cursor_cli.sh scripts/orch/setup_cursor_runner.sh install/adapters/cursor.sh 2>/dev/null | wc -l | tr -d ' ')
[ "$c2" -eq 0 ] && pass "C2 cursor scripts == 0 (got $c2)" || miss "C2 cursor scripts == 0 (got $c2)"

# C3 — no CursorBackend class (default runner can't be cursor)
c3=$(grep -c "class CursorBackend" "$LIB/runner_backend.dart" 2>/dev/null || true)
[ "${c3:-0}" -eq 0 ] && pass "C3 CursorBackend removed (got $c3)" || miss "C3 CursorBackend removed (got $c3)"

# C4 — crew no longer default-OFF (the `== '1'` opt-in gate is gone)
c4=$(grep -c "ADF_REQUIREMENTS_CREW'] == '1'" "$LIB/requirements_crew_runner.dart" 2>/dev/null || true)
[ "${c4:-0}" -eq 0 ] && pass "C4 crew default-on (opt-in gate removed) (got $c4)" || miss "C4 crew default-on (got $c4, want 0)"

# C5 — crew default exported by the launcher
c5=$(grep -c "ADF_REQUIREMENTS_CREW" scripts/orch/run_server_local_llm.sh 2>/dev/null || true)
[ "${c5:-0}" -ge 1 ] && pass "C5 crew in launcher (got $c5)" || miss "C5 crew in launcher (want >=1, got ${c5:-0})"

# C8 — no @orch-orchestrator literal generated by the pipeline planner
c8=$(grep -c "@orch-orchestrator" "$LIB/pipeline_planner.dart" 2>/dev/null || true)
[ "$c8" -eq 0 ] && pass "C8 no @orch-orchestrator in planner (got $c8)" || miss "C8 no @orch-orchestrator in planner (got $c8, want 0)"

# C11 — the resolver defaults to .adf/orchestration (CURSOR-6)
c11=$(grep -c 'return .\$repoRoot/\$_genericRelative' "$LIB/orchestration_paths.dart" 2>/dev/null || true)
g11=$(grep -c "_genericRelative = '.adf/orchestration'" "$LIB/orchestration_paths.dart" 2>/dev/null || true)
{ [ "${c11:-0}" -ge 1 ] && [ "${g11:-0}" -ge 1 ]; } && pass "C11 resolver defaults to .adf/orchestration" || miss "C11 resolver defaults to .adf (got default=$c11 generic=$g11)"

# C12 — the live data is migrated to .adf/orchestration (no-loss; legacy kept)
if [ -d .adf/orchestration/features ]; then
  n=$(ls -1 .adf/orchestration/features 2>/dev/null | wc -l | tr -d ' ')
  [ "${n:-0}" -ge 1 ] && pass "C12 .adf/orchestration migrated ($n features)" || miss "C12 .adf/orchestration empty"
else
  miss "C12 .adf/orchestration not present"
fi

echo "-----"
if [ "$fail" -eq 0 ]; then echo "EVAL: ALL MEASURED CRITERIA MET ✅"; else echo "EVAL: criteria unmet ❌"; fi
exit $fail
